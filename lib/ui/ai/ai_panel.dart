/// Where an AI deep link goes (spec §9.4 `deepLink`).
void openAiLink(BuildContext context, String link) => switch (link) {
      'planner' => context.push('/loans/planner'),
      'budgets' => context.go('/plans?seg=budgets'),
      'goals' => context.go('/plans?seg=goals'),
      'salary' => context.push('/settings/salary'),
      'inbox' => context.go('/activity'),
      _ => null,
    };

String? aiLinkLabel(String link) => switch (link) {
      'planner' => 'Open payoff planner',
      'budgets' => 'Open budgets',
      'goals' => 'Open goals',
      'salary' => 'Open salary',
      'inbox' => 'Open activity',
      _ => null,
    };

/// Spec §9.4 guardrail 4.
class AiLabel extends StatelessWidget {
  const AiLabel({super.key, this.date});
  final String? date;

  @override
  Widget build(BuildContext context) => Text(
        'Generated by AI · may be wrong${date == null ? '' : ' · $date'}',
        style: PaisaText.hint.copyWith(color: context.colors.ink3),
      );
}

/// An "ask the AI" button with its answer underneath. Hidden while the AI
/// assistant is off (acceptance 16). Nothing is sent until it is tapped.
class AiPanel<T> extends ConsumerStatefulWidget {
  const AiPanel({super.key, required this.label, required this.run, required this.result, this.enabled = true});

  final String label;
  final Future<T> Function(AiService ai) run;
  final Widget Function(BuildContext context, T value) result;

  /// False when there is nothing to ask about yet.
  final bool enabled;

  @override
  ConsumerState<AiPanel<T>> createState() => _AiPanelState<T>();
}

class _AiPanelState<T> extends ConsumerState<AiPanel<T>> {
  T? _value;
  AiError? _error;
  bool _busy = false;

  Future<void> _ask() async {
    setState(() {
      _busy = true;
      _error = null;
    });
    try {
      final v = await runAi(() => widget.run(ref.read(aiServiceProvider)));
      if (mounted) setState(() => _value = v);
    } on AiError catch (e) {
      if (mounted) setState(() => _error = e);
    } finally {
      if (mounted) setState(() => _busy = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    final on = ref.watch(aiSettingsProvider).value?.enabled ?? false;
    if (!on) return const SizedBox.shrink();
    final value = _value;
    return Padding(
      padding: const EdgeInsets.only(top: 12),
      child: Column(crossAxisAlignment: CrossAxisAlignment.stretch, children: [
        if (value != null) ...[
          PaisaCard(
            child: Column(crossAxisAlignment: CrossAxisAlignment.stretch, children: [
              widget.result(context, value),
              const SizedBox(height: 10),
              const AiLabel(),
            ]),
          ),
          const SizedBox(height: 10),
        ],
        if (_error != null) ...[Note(_error!.message, tone: Tone.amber), const SizedBox(height: 10)],
        PaisaButton(
          label: _busy ? 'Asking AI…' : (value == null ? widget.label : 'Ask again'),
          icon: PaisaIcons.bolt,
          variant: ButtonVariant.outline,
          onPressed: _busy || !widget.enabled ? null : _ask,
        ),
      ]),
    );
  }
}

/// A bulleted line in an AI answer.
class AiBullet extends StatelessWidget {
  const AiBullet(this.text, {super.key});
  final String text;

  @override
  Widget build(BuildContext context) {
    final c = context.colors;
    return Padding(
      padding: const EdgeInsets.only(top: 6),
      child: Row(crossAxisAlignment: CrossAxisAlignment.start, children: [
        Text('•  ', style: PaisaText.body.copyWith(color: c.ink3)),
        Expanded(child: Text(text, style: PaisaText.body.copyWith(color: c.ink2))),
      ]),
    );
  }
}
